import Foundation

struct IndexError: Error, CustomStringConvertible {
  let description: String
  init(_ description: String) { self.description = description }
}

struct NumberedCall: Equatable {
  let number: UInt64
  let symbol: String
}

enum Catalogue {
  static func publicNames(in document: String) throws -> [String] {
    guard let header = document.range(of: "\n## 23. Call index\n"),
      let end = document[header.upperBound...].range(of: "\n## ")
    else {
      throw IndexError("Missing LibTessera §23")
    }
    let section = document[header.upperBound..<end.lowerBound]
      .split(whereSeparator: \.isWhitespace).joined(separator: " ")
    guard let start = section.range(of: "Handle / Object ("),
      let footer = section.range(of: " Plus the tessera.system"),
      start.lowerBound < footer.lowerBound
    else { throw IndexError("Missing call catalogue") }
    let body = String(section[start.lowerBound..<footer.lowerBound]) as NSString
    let regex = try NSRegularExpression(
      pattern: #"([A-Z][a-zA-Z]*(?: / [A-Z][a-zA-Z]*)?) \(([0-9]+)\) "#)
    let groups = regex.matches(in: body as String, range: NSRange(location: 0, length: body.length))
    guard groups.first?.range.location == 0 else { throw IndexError("Malformed call groups") }
    var names: [String] = []
    for (i, group) in groups.enumerated() {
      let lower = NSMaxRange(group.range)
      let upper = i + 1 == groups.count ? body.length : groups[i + 1].range.location
      let calls = body.substring(with: NSRange(location: lower, length: upper - lower))
        .trimmingCharacters(in: .whitespaces).components(separatedBy: ", ")
      guard calls.count == Int(body.substring(with: group.range(at: 2))) else {
        throw IndexError("Wrong group count: \(body.substring(with: group.range(at: 1)))")
      }
      for call in calls {
        let name = call.hasSuffix(" A") ? String(call.dropLast(2)) : call
        _ = try symbol(for: name)
        names.append(name)
      }
    }
    return names
  }

  private static func symbol(for name: String) throws -> String {
    guard
      name.range(of: #"\A[A-Z][A-Za-z0-9]*\.[a-z][A-Za-z0-9]*\z"#, options: .regularExpression)
        != nil
    else {
      throw IndexError("Invalid call name: \(name)")
    }
    let parts = name.split(separator: ".")
    return parts[0].prefix(1).lowercased() + parts[0].dropFirst()
      + parts[1].prefix(1).uppercased() + parts[1].dropFirst()
  }

  static func number(_ names: [String], extensions: [String]) throws -> [NumberedCall] {
    guard names.count < 65536 else { throw IndexError("Public numbers reach private bank") }
    var result: [NumberedCall] = []
    var symbols: Set<String> = []
    func emit(_ bank: [String], at first: UInt64) throws -> UInt64 {
      var last = first
      for (i, name) in bank.sorted().enumerated() {
        let (number, overflow) = first.addingReportingOverflow(UInt64(i))
        let symbol = try symbol(for: name)
        guard !overflow, symbols.insert(symbol).inserted else {
          throw IndexError("Overflow or duplicate: \(name)")
        }
        result.append(NumberedCall(number: number, symbol: symbol))
        last = number
      }
      return last
    }
    _ = try emit(names, at: 1)
    var base: UInt64 = 0x10000
    var bank: [String] = []
    for entry in extensions {
      if entry.hasPrefix("@") {
        let marker = entry.dropFirst()
        let next = marker.hasPrefix("0x") ? UInt64(marker.dropFirst(2), radix: 16) : UInt64(marker)
        let last = try emit(bank, at: base)
        guard let next, !bank.isEmpty, next > last else {
          throw IndexError("Bad private bank: \(entry)")
        }
        base = next
        bank.removeAll(keepingCapacity: true)
      } else {
        bank.append(entry)
      }
    }
    if extensions.last?.hasPrefix("@") == true { throw IndexError("Empty private bank") }
    _ = try emit(bank, at: base)
    return result
  }

  static func render(_ calls: [NumberedCall]) -> String {
    "// Generated by TarwinSyscall's call-index tool. Do not edit.\npublic enum TarwinCall {\n"
      + calls.map { "    public static let \($0.symbol): UInt64 = \($0.number)\n" }.joined() + "}\n"
  }
}
