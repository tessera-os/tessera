"""Generate matching train-private Kira call numbers for kernel and library."""
import argparse
from pathlib import Path
import re
import sys

PACKAGE = Path(__file__).resolve().parents[1]
PACKAGES = PACKAGE.parents[1]
INDEX = PACKAGES / "tessera/roadmap/16-libtessera.md"
EXTENSIONS = PACKAGE / "extensions.txt"
OUTPUTS = (
    PACKAGE / "app/CallNumbers.kira",
    PACKAGES / "libtessera/app/Backend/Tarwin/CallNumbers.kira",
)
NAME = r"[A-Z][A-Za-z0-9]*\.[a-z][A-Za-z0-9]*"
SECTION = re.compile(r"^## 23\. Call index\s*$(.*?)^## ", re.M | re.S)
GROUP = re.compile(r"([A-Z][a-zA-Z]*(?: / [A-Z][a-zA-Z]*)?) \((\d+)\) ")
EXTENSION_BASE = 65536


def public_names(document):
    section = SECTION.search(document)
    if not section:
        raise ValueError("missing LibTessera §23")
    # Only the catalogue: File.read/write also occur in the introductory prose.
    body = " ".join(section[1].split())
    begin = body.index("Handle / Object (")
    end = body.index(" Plus the tessera.system", begin)
    groups = GROUP.split(body[begin:end])
    if groups[0] or len(groups) == 1:
        raise ValueError("unrecognized call index")
    result = []
    for title, count, entries in zip(groups[1::3], groups[2::3], groups[3::3]):
        calls = entries.strip().split(", ")
        if len(calls) != int(count):
            raise ValueError(f"{title}: expected {count} named calls")
        for call in calls:
            match = re.fullmatch(f"({NAME})(?: A)?", call)
            if not match:
                raise ValueError(f"{title}: malformed entry {call!r}")
            result.append(match[1])
    return result


def catalogue(public, extensions):
    if len(public) >= EXTENSION_BASE:
        raise ValueError("base index reaches extension range")
    result = []
    symbols = set()
    for first, names in [(1, public), (EXTENSION_BASE, extensions)]:
        for number, name in enumerate(sorted(names), first):
            if not re.fullmatch(NAME, name):
                raise ValueError(f"invalid call name {name!r}")
            domain, method = name.split(".")
            symbol = domain[:1].lower() + domain[1:] + method[0].upper() + method[1:]
            if symbol in symbols:
                raise ValueError(f"duplicate call or symbol: {name}")
            symbols.add(symbol)
            result.append((number, symbol))
    return result


def render(calls, kernel):
    visibility = "public " if kernel else ""
    return ("// Generated by tarwin-syscall/tools/call_index.py. Do not edit.\n"
            + visibility + "namespace TarwinCall {\n"
            + "".join(f"    let {symbol}: U64 = {number}\n" for number, symbol in calls)
            + "}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on missing or stale output")
    args = parser.parse_args()
    extensions = [s for s in EXTENSIONS.read_text().splitlines() if s and not s.startswith("#")]
    calls = catalogue(public_names(INDEX.read_text()), extensions)
    for i, path in enumerate(OUTPUTS):
        source = render(calls, kernel=i == 0)
        if args.check:
            if not path.exists() or source != path.read_text():
                sys.exit(f"{path}: missing or stale call numbers")
        else:
            path.write_text(source)


if __name__ == "__main__":
    main()
