import XCTest

@testable import TarwinIPC

final class TarwinIPCTests: XCTestCase {
  func testDomainContracts() {
    let ring = RingGeometry(count: 64, stride: 64)
    XCTAssertTrue(ring.fits(12288))
    XCTAssertFalse(ring.fits(12287))
    XCTAssertEqual(ring.offset(64, false), 4096)
    XCTAssertEqual(ring.offset(127, true), 12224)
    let wide = RingGeometry(count: 65536, stride: 128)
    XCTAssertTrue(wide.fits(16_781_312))
    let badCount = RingGeometry(count: 96, stride: 64)
    let badStride = RingGeometry(count: 64, stride: 65)
    XCTAssertFalse(badCount.valid())
    XCTAssertFalse(badStride.valid())
    XCTAssertTrue(ringProducerValid(400, 464, 400, 64))
    XCTAssertFalse(ringProducerValid(400, 465, 400, 64))
    XCTAssertFalse(ringProducerValid(400, 399, 395, 64))
    XCTAssertFalse(ringConsumerValid(400, 465, 464))
    XCTAssertTrue(ringHeaderAllowed(0x474e_5254, 1, 0))
    XCTAssertFalse(ringHeaderAllowed(0x474e_5254, 1, 1))
    var credits = PortCredits(capacity: 2, pending: 0, available: 0)
    XCTAssertTrue(credits.reserve())
    XCTAssertTrue(credits.postUser())
    XCTAssertFalse(credits.reserve())
    XCTAssertFalse(credits.postUser())
    XCTAssertTrue(credits.complete())
    XCTAssertFalse(credits.complete())
    XCTAssertEqual(credits.free(), 0)
    XCTAssertTrue(credits.take())
    XCTAssertTrue(credits.take())
    XCTAssertFalse(credits.take())
    XCTAssertEqual(credits.free(), 2)
    var call = ServiceCall(transaction: 17, deadline: 40, context: 5, server: 0, state: .waiting)
    XCTAssertTrue(call.receive(8, 20))
    XCTAssertFalse(call.receive(9, 20))
    XCTAssertEqual(call.donatedTo(9), 0)
    XCTAssertEqual(call.donatedTo(8), 5)
    XCTAssertFalse(call.reply(18, 8, 21))
    XCTAssertFalse(call.reply(17, 9, 21))
    XCTAssertFalse(call.reply(17, 8, 40))
    XCTAssertEqual(call.state, .timedOut)
    XCTAssertFalse(call.cancel(true))
    XCTAssertEqual(call.donatedTo(8), 0)
    var peer = ServiceCall(transaction: 1, deadline: 99, context: 6, server: 0, state: .waiting)
    XCTAssertTrue(peer.cancel(true))
    XCTAssertFalse(peer.receive(2, 0))
    XCTAssertEqual(peer.state, .peerClosed)
    var ok = ServiceCall(transaction: 9, deadline: 99, context: 6, server: 0, state: .waiting)
    XCTAssertTrue(ok.receive(1, 0))
    XCTAssertTrue(ok.reply(9, 1, 1))
    XCTAssertFalse(ok.cancel(false))
    XCTAssertTrue(channelMessageFits(65536, 64))
    XCTAssertFalse(inlineCall(129, 4))
  }
}
